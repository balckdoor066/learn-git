function PixelRects({ rows, palette }: { rows: string[]; palette: Palette }) {
  return rows.flatMap((row, y) => row.split('').map((cell, x) => {
    const fill = palette[cell];
    if (!fill || fill === 'transparent') return null;
    return <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={fill} />;
  }));
}

export function AgentSprite({ agent, size = 6 }: { agent: Agent; size?: number }) {
  const spec = spriteSpecs[agent.sprite];
  const scale = Math.max(0.45, size / 6);
  return (
    <div
      className={'sprite-shell svg-sprite-shell ' + agent.status}
      style={{ '--agent-accent': agent.accent, '--sprite-scale': scale, '--sprite-delay': spec.delay } as CSSProperties}
      aria-hidden="true"
    >
      <svg className="agent-svg-sprite" viewBox="0 0 32 48" shapeRendering="crispEdges">
        <rect x="6" y="45" width="22" height="3" fill="rgba(0,0,0,.42)" />
        <PixelRects rows={spec.rows} palette={spec.palette} />
      </svg>
      <span className={'sprite-signal ' + agent.status} />
    </div>
  );
}
